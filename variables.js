//hoistinng  //підняття змінних вгору. let і const не піднімаються вгору, на відміну від var.

//let
let thisIsMyFirstVariable = "Hello World!";

//const
const thisIsMySecondVariable = 3.14;
console.log(thisIsMySecondVariable);

thisIsMyFirstVariable = 100;
console.log(thisIsMyFirstVariable);




//В автотестах правильно використовувати const замість let, щоб уникнути випадкових змін значень змінних.

//var
